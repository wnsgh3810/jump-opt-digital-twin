def find_target_page():
    url = f"https://api.notion.com/v1/blocks/{PARENT}/children?page_size=100"
    found = None
    while url:
        r = requests.get(url, headers=H)
        r.raise_for_status()
        data = r.json()
        for b in data.get("results", []):
            if b.get("type") == "child_page":
                title = b["child_page"].get("title", "")
                if title.startswith(TARGET_PREFIX):
                    found = b["id"]
        if data.get("has_more") and data.get("next_cursor"):
            url = f"https://api.notion.com/v1/blocks/{PARENT}/children?page_size=100&start_cursor={data['next_cursor']}"
        else:
            url = None
    return found


def append(page, blocks):
    for i in range(0, len(blocks), 80):
        chunk = blocks[i:i + 80]
        for attempt in range(6):
            r = requests.patch(f"https://api.notion.com/v1/blocks/{page}/children",
                               headers={**H, "Content-Type": "application/json"},
                               json={"children": chunk})
            if r.status_code == 429:
                wait = float(r.headers.get("Retry-After", 2))
                print(f"429 — retry in {wait}s", flush=True)
                time.sleep(wait)
                continue
            if r.status_code != 200:
                raise RuntimeError(r.text[:800])
            break
        else:
            raise RuntimeError("429 재시도 초과")
        time.sleep(0.6)


